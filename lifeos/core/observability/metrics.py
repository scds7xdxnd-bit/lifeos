def _safe_ratio(numerator: int, denominator: int) -> float:
    if denominator <= 0:
        return 0.0
    return max(0.0, float(numerator) / float(denominator))


def _coerce_quality_metadata(
    quality_metadata: Mapping[str, object] | None,
    findings_total: int,
    findings_with_evidence: int,
) -> dict[str, object]:
    if isinstance(quality_metadata, Mapping):
        return dict(quality_metadata)
    coverage = _safe_ratio(findings_with_evidence, findings_total)
    return {
        "findings_total": findings_total,
        "findings_with_evidence": findings_with_evidence,
        "evidence_coverage_ratio": coverage,
        "structure_gaps": [],
        "sparse_domains": [],
    }


def _is_low_quality_metadata(quality_metadata: Mapping[str, object] | None) -> bool:
    if not isinstance(quality_metadata, Mapping):
        return False
    findings_total = int(quality_metadata.get("findings_total") or 0)
    coverage = float(quality_metadata.get("evidence_coverage_ratio") or 0.0)
    structure_gaps = list(quality_metadata.get("structure_gaps") or [])
    sparse_domains = list(quality_metadata.get("sparse_domains") or [])
    if findings_total == 0:
        return True
    return coverage < _LOW_COVERAGE_THRESHOLD or bool(structure_gaps) or bool(sparse_domains)


def _quality_state(quality_metadata: Mapping[str, object] | None) -> str:
    if not isinstance(quality_metadata, Mapping):
        return "unknown"
    findings_total = int(quality_metadata.get("findings_total") or 0)
    coverage = float(quality_metadata.get("evidence_coverage_ratio") or 0.0)
    structure_gaps = list(quality_metadata.get("structure_gaps") or [])
    sparse_domains = list(quality_metadata.get("sparse_domains") or [])
    if findings_total == 0:
        return "empty"
    if coverage < _LOW_COVERAGE_THRESHOLD:
        return "low_coverage"
    if bool(structure_gaps) or bool(sparse_domains):
        return "needs_refine"
    return "sufficient"


