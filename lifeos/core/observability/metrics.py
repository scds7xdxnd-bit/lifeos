def record_inquiry_generated(
    *,
    latency_seconds: float | None,
    is_empty: bool,
    findings_total: int,
    findings_with_evidence: int,
    quality_metadata: Mapping[str, object] | None = None,
    domain: str | None = None,
    profile: str | None = None,
    profile_version: str | None = None,
    strategy: str | None = None,
    strategy_version: str | None = None,
    expert_mode: bool | str | None = None,
) -> None:
    """Record focused inquiry brief generation and coverage stats."""
    global _inquiry_generated_count
    global _inquiry_empty_count
    global _inquiry_findings_count
    global _inquiry_findings_with_evidence_count
    global _inquiry_low_coverage_count

    domain_labels = _domain_metric_labels(
        domain=domain,
        profile=profile,
        profile_version=profile_version,
        strategy=strategy,
        strategy_version=strategy_version,
        expert_mode=expert_mode,
    )
    INQUIRY_GENERATED_TOTAL.inc()
    INQUIRY_GENERATED_BY_DOMAIN_TOTAL.labels(**domain_labels).inc()
    _inquiry_generated_count += 1

    if latency_seconds is not None:
        INQUIRY_GENERATION_LATENCY_SECONDS.observe(max(0.0, latency_seconds))
        INQUIRY_GENERATION_LATENCY_SECONDS_BY_DOMAIN.labels(**domain_labels).observe(max(0.0, latency_seconds))

    if is_empty:
        INQUIRY_EMPTY_BRIEF_TOTAL.inc()
        INQUIRY_EMPTY_BRIEF_BY_DOMAIN_TOTAL.labels(**domain_labels).inc()
        _inquiry_empty_count += 1

    findings_total = max(0, int(findings_total))
    findings_with_evidence = max(0, min(findings_total, int(findings_with_evidence)))
    if findings_total:
        INQUIRY_FINDINGS_TOTAL.inc(findings_total)
        INQUIRY_FINDINGS_WITH_EVIDENCE_TOTAL.inc(findings_with_evidence)
        INQUIRY_FINDINGS_BY_DOMAIN_TOTAL.labels(**domain_labels).inc(findings_total)
        INQUIRY_FINDINGS_WITH_EVIDENCE_BY_DOMAIN_TOTAL.labels(**domain_labels).inc(findings_with_evidence)
        _inquiry_findings_count += findings_total
        _inquiry_findings_with_evidence_count += findings_with_evidence

    quality = _coerce_quality_metadata(quality_metadata, findings_total, findings_with_evidence)
    state = _quality_state(quality)
    INQUIRY_QUALITY_STATE_TOTAL.labels(state=state).inc()
    INQUIRY_QUALITY_STATE_BY_DOMAIN_TOTAL.labels(state=state, **domain_labels).inc()
    if state == "low_coverage":
        INQUIRY_LOW_COVERAGE_TOTAL.inc()
        INQUIRY_LOW_COVERAGE_BY_DOMAIN_TOTAL.labels(**domain_labels).inc()
        _inquiry_low_coverage_count += 1

    INQUIRY_EMPTY_BRIEF_RATE.set(_safe_ratio(_inquiry_empty_count, _inquiry_generated_count))
    INQUIRY_EVIDENCE_COVERAGE_RATIO.set(_safe_ratio(_inquiry_findings_with_evidence_count, _inquiry_findings_count))
    INQUIRY_LOW_COVERAGE_RATE.set(_safe_ratio(_inquiry_low_coverage_count, _inquiry_generated_count))
    INQUIRY_ERROR_RATE.set(_safe_ratio(_inquiry_error_count, _inquiry_generated_count + _inquiry_error_count))


