def _domain_metric_labels(
    *,
    domain: str | None,
    profile: str | None,
    profile_version: str | None,
    strategy: str | None,
    strategy_version: str | None,
    expert_mode: bool | str | None,
) -> dict[str, str]:
    def _text(value: object | None, *, default: str = "unknown") -> str:
        rendered = str(value or "").strip()
        return rendered or default

    if isinstance(expert_mode, str):
        expert = expert_mode.strip().lower() in {"1", "true", "yes", "on"}
    else:
        expert = bool(expert_mode)
    return {
        "domain": _text(domain),
        "profile": _text(profile),
        "profile_version": _text(profile_version),
        "strategy": _text(strategy),
        "strategy_version": _text(strategy_version),
        "expert_mode": "true" if expert else "false",
    }


