def record_inquiry_refine_after_low_quality(
    previous_quality_metadata: Mapping[str, object] | None,
    *,
    domain: str | None = None,
    profile: str | None = None,
    profile_version: str | None = None,
    strategy: str | None = None,
    strategy_version: str | None = None,
    expert_mode: bool | str | None = None,
) -> None:
    """Record refine operations that occur after a low-quality brief."""
    global _inquiry_refine_after_low_quality_count
    if not _is_low_quality_metadata(previous_quality_metadata):
        return
    domain_labels = _domain_metric_labels(
        domain=domain,
        profile=profile,
        profile_version=profile_version,
        strategy=strategy,
        strategy_version=strategy_version,
        expert_mode=expert_mode,
    )
    INQUIRY_REFINE_AFTER_LOW_QUALITY_TOTAL.inc()
    INQUIRY_REFINE_AFTER_LOW_QUALITY_BY_DOMAIN_TOTAL.labels(**domain_labels).inc()
    _inquiry_refine_after_low_quality_count += 1
    INQUIRY_REFINE_AFTER_LOW_QUALITY_RATE.set(
        _safe_ratio(_inquiry_refine_after_low_quality_count, _inquiry_refined_count)
    )


def record_inquiry_error(
    stage: str,
    error_type: str,
    *,
    domain: str | None = None,
    profile: str | None = None,
    profile_version: str | None = None,
    strategy: str | None = None,
    strategy_version: str | None = None,
    expert_mode: bool | str | None = None,
) -> None:
    """Record focused inquiry pipeline errors."""
    global _inquiry_error_count
    domain_labels = _domain_metric_labels(
        domain=domain,
        profile=profile,
        profile_version=profile_version,
        strategy=strategy,
        strategy_version=strategy_version,
        expert_mode=expert_mode,
    )
    INQUIRY_ERRORS_TOTAL.labels(stage=stage or "unknown", error_type=error_type or "unknown").inc()
    INQUIRY_ERRORS_BY_DOMAIN_TOTAL.labels(
        stage=stage or "unknown",
        error_type=error_type or "unknown",
        **domain_labels,
    ).inc()
    _inquiry_error_count += 1
    INQUIRY_ERROR_RATE.set(_safe_ratio(_inquiry_error_count, _inquiry_generated_count + _inquiry_error_count))


